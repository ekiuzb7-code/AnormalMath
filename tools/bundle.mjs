// language: Node ESM, file: tools/bundle.mjs
// Flattens the ES-module app into one classic script so a WebView can load it
// from file:// without CORS. Every module becomes a function scope; imports are
// rewritten to a tiny require().
import fs from "node:fs";
import path from "node:path";

const SRC = path.resolve("js");
const OUT = path.resolve("mobile/www/bundle.js");

const ORDER = [
  "engine",
  "content/math",
  "content/arithmetic",
  "content/algebra",
  "content/functions",
  "content/geometry",
  "content/trigonometry",
  "content/calculus",
  "content/statistics",
  "content/probability",
  "content/sat",
  "content/index",
  "app",
];

function resolveId(fromId, spec) {
  if (!spec.startsWith(".")) return spec.replace(/\.js$/, "");
  const fromDir = fromId.includes("/") ? fromId.slice(0, fromId.lastIndexOf("/")) : "";
  const joined = path.posix.normalize(path.posix.join(fromDir, spec));
  return joined.replace(/\.js$/, "");
}

function transform(id, code) {
  const exported = [];

  // import { a, b } from "./x.js";  ->  const { a, b } = __req("x");
  code = code.replace(
    /import\s*\{([^}]+)\}\s*from\s*["']([^"']+)["'];?/g,
    (_m, names, spec) => `const {${names}} = __req(${JSON.stringify(resolveId(id, spec))});`,
  );

  // export const NAME = ... / export function NAME(...)
  code = code.replace(/export\s+(const|let|function)\s+([A-Za-z_$][\w$]*)/g, (_m, kind, name) => {
    exported.push(name);
    return `${kind} ${name}`;
  });

  const assigns = exported.map((n) => `__exports.${n} = ${n};`).join("\n");
  return `__def(${JSON.stringify(id)}, function (__req, __exports) {\n${code}\n${assigns}\n});`;
}

const parts = [
  `/* AnormalMath bundle — generated by tools/bundle.mjs */
(function () {
  "use strict";
  var __defs = {}, __cache = {};
  function __def(id, fn) { __defs[id] = fn; }
  function __req(id) {
    if (__cache[id]) return __cache[id];
    var fn = __defs[id];
    if (!fn) throw new Error("module not found: " + id);
    var exports = (__cache[id] = {});
    fn(__req, exports);
    return exports;
  }
`,
];

for (const id of ORDER) {
  const file = path.join(SRC, `${id}.js`);
  const code = fs.readFileSync(file, "utf8");
  parts.push(transform(id, code));
  parts.push("");
}

parts.push(`  __req("app");\n})();\n`);

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, parts.join("\n"), "utf8");
console.log("bundle written:", OUT, fs.statSync(OUT).size, "bytes");
